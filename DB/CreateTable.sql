
CREATE TABLE public.users (
    id int4 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar NOT NULL,
    password varchar NOT NULL
);

CREATE TABLE public.types (
    id int4 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar NOT NULL
);

CREATE TABLE public.pokemons (
    id int4 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    shiny bool DEFAULT false NOT NULL,
    image varchar,
    description_pt text
);

CREATE TABLE public.team (
    id int4 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar NOT NULL,
    style varchar,
    image varchar,
    id_user int4 NOT NULL REFERENCES public.users(id) ON DELETE CASCADE
);

CREATE TABLE public.pokemon_types (
    pokemon_id int4 NOT NULL REFERENCES public.pokemons(id) ON DELETE CASCADE,
    type_id int4 NOT NULL REFERENCES public.types(id) ON DELETE CASCADE,
    slot int4 NOT NULL,
    PRIMARY KEY (pokemon_id, type_id)
);

CREATE TABLE public.pokemon_team (
    id int4 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pokemon int4 NOT NULL REFERENCES public.pokemons(id) ON DELETE CASCADE,
    id_team int4 NOT NULL REFERENCES public.team(id) ON DELETE CASCADE,
    shiny bool DEFAULT false NOT NULL
);

CREATE TABLE public.pokemon_user (
    id int4 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_user int4 NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    id_pokemon int4 NOT NULL REFERENCES public.pokemons(id) ON DELETE CASCADE,
    catch bool DEFAULT false NOT NULL,
    favority bool DEFAULT false NOT NULL,
    catch_shiny bool DEFAULT false NOT NULL,
    favority_shiny bool DEFAULT false NOT NULL
);